export type TKey = keyof typeof id;
const dict = { id, en } as const;

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string | number>) => string };
const I18n = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return localStorage.getItem('bpd-lang') === 'en' ? 'en' : 'id'; } catch { return 'id'; }
  });
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('bpd-lang', l); } catch { /* abaikan */ }
  };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<Ctx>(() => ({
    lang, setLang,
    t: (k, vars) => {
      let s: string = dict[lang][k];
      if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v));
      return s;
    },
  }), [lang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18n);
  if (!c) throw new Error('I18nProvider missing');
  return c;
}

